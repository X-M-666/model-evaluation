def generate_tasks(
    dims: list[str] | None = None,
    seed: int | None = None,
    num_questions: int | None = None,
) -> list[dict[str, Any]]:
    """从题库池按维度抽取题目，生成任务集。

    Args:
        dims: 需覆盖的维度列表（默认全部七维度）；同一维度只会抽 1 题。
        seed: 随机种子；固定 seed 可复现同一任务集（便于对比不同模型）。
        num_questions: 题目数量上限（如 3/5/7）；从 dims 中随机抽样该数量的
            维度出题，超过 dims 长度时以 dims 长度为准。
    """
    if seed is not None:
        random.seed(seed)
    selected_dims = dims or list(DIMENSIONS)
    if num_questions is not None:
        selected_dims = random.sample(selected_dims, min(num_questions, len(selected_dims)))
    tasks: list[dict[str, Any]] = []
    for dim in selected_dims:
        pool = QUESTION_POOL.get(dim, [])
        if not pool:
            continue
        q = random.choice(pool)
        q = {k: v for k, v in q.items()}
        q["id"] = f"T{len(tasks) + 1}"
        tasks.append(q)
    return tasks


def build_task_set(
    dims: list[str] | None = None,
    seed: int | None = None,
    num_questions: int | None = None,
) -> dict[str, Any]:
    """生成完整任务集 dict（与 .eval/tasks.json 结构一致）。"""
    tasks = generate_tasks(dims, seed, num_questions)
    stability_ids = [
        t["id"] for t in tasks if t["dimension"] == "效率与稳定性"
    ]
    meta = {
        "scope": "七大能力维度",
        "total": len(tasks),
        "created_by": "webapp",
        "multimodal": "N/A",
        "num_questions": num_questions,
    }
    if stability_ids:
        meta["eval_flags"] = {"stability_repeat": {stability_ids[0]: 2}}
    return {"meta": meta, "tasks": tasks}


def build_task_set_from_dataset(dataset: dict[str, Any]) -> dict[str, Any]:
    """从上传的评测集构建任务集（结构与 build_task_set 输出一致）。"""
    tasks = dataset.get("tasks", [])
    if not tasks:
        raise ValueError("评测集 tasks 为空")

    # 补全缺失字段并重新编号
    for i, t in enumerate(tasks):
        t.setdefault("id", f"T{i+1}")
        t.setdefault("dimension", "自定义")
        t.setdefault("benchmark", "自定义评测集")
        t.setdefault("difficulty", "进阶")
        t.setdefault("test_cases", [])
        t.setdefault("rubric_note", "【仅评审可见】满分10分。")

    # 检测效率稳定性维度
    stability_ids = [t["id"] for t in tasks if t["dimension"] == "效率与稳定性"]
    dims = list({t["dimension"] for t in tasks})

    meta = {
        "scope": "自定义评测集",
        "total": len(tasks),
        "created_by": "webapp",
        "multimodal": "N/A",
        "dataset_name": dataset.get("name", ""),
        "dataset_description": dataset.get("description", ""),
    }
    if stability_ids:
        meta["eval_flags"] = {"stability_repeat": {stability_ids[0]: 2}}
    return {"meta": meta, "tasks": tasks}


