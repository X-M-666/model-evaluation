def _demo_tasks() -> list[dict[str, Any]]:
    tasks = []
    for idx, (tid, doc) in enumerate(_DEMO_DOCS.items(), start=1):
        tasks.append({
            "id": tid,
            "dimension": "知识能力",
            "benchmark": f"RAG 演示题 {idx}（生成式，仅依据参考文档）",
            "difficulty": "进阶",
            "prompt": _DEMO_PROMPTS[tid],
            "expected": "",
            "rubric_note": (
                "满分 10 分分档：8-10 分：准确引用参考文档要点，分点清晰，无文档外臆造；"
                "5-7 分：要点基本正确但引用不完整或混入少量常识；"
                "0-4 分：大段偏离文档、臆造事实或回答与问题无关。"
            ),
            "type": "生成式",
            "tags": ["rag", "context", "demo"],
            "context": doc,
            "excluded_from_total": False,
        })
    return validate_standard_dataset({
        "name": DEMO_NAME,
        "description": DEMO_DESC,
        "tasks": tasks,
    })["tasks"]


def ensure_demo_rag_dataset() -> None:
    """评测集目录尚无 rag_demo 数据集时写入内置演示集（source="builtin_demo"）。

    幂等：已存在同名数据集（含用户上传覆盖）则跳过，不回退。
    """
    if storage.load_dataset(DEMO_NAME) is not None:
        return
    storage.save_dataset(DEMO_NAME, {
        "name": DEMO_NAME,
        "description": DEMO_DESC,
        "source": "builtin_demo",
        "version": "v1",
        "tasks": _demo_tasks(),
    })