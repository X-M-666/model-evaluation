# -*- coding: utf-8 -*-
"""评测集解析器单元测试（issue #11）。

覆盖 parse_json / parse_csv / parse_markdown / parse_txt 的正常、边界与恶意输入，
以及扩展名注册表 get_parser / supported_extensions 的路由行为。
"""
from __future__ import annotations

import json
import re

import pytest

from backend.engine.parsers import (
    PARSER_REGISTRY,
    get_parser,
    parse_csv,
    parse_json,
    parse_markdown,
    parse_txt,
    supported_extensions,
)
from backend.engine.datasets import DatasetValidationError

XSS = '<script>alert("x")</script>'
AUTO_NAME = re.compile(r"^评测集_\d{8}_\d{6}$")


# ---------------- parse_json ----------------

def test_json_full_format_ok():
    data = parse_json('{"name":"N","description":"D","tasks":[{"id":"t1","dimension":"知识",'
                      '"prompt":"p","expected":"e"}]}')
    assert data["name"] == "N"
    assert data["description"] == "D"
    assert data["tasks"][0]["id"] == "t1"
    assert data["tasks"][0]["prompt"] == "p"


def test_json_broken_raises():
    with pytest.raises(ValueError, match="JSON 解析失败"):
        parse_json("{not json")


def test_json_top_level_array_raises():
    with pytest.raises(ValueError, match="顶层必须是对象"):
        parse_json('[{"prompt":"p"}]')


def test_json_empty_tasks_raises():
    with pytest.raises(ValueError, match="缺少 tasks"):
        parse_json('{"name":"N","tasks":[]}')


def test_json_missing_name_autogenerated():
    data = parse_json('{"tasks":[{"prompt":"p","expected":"e"}]}')
    assert AUTO_NAME.match(data["name"])


def test_json_xss_payload_passes_through_as_data():
    """XSS 载荷只是数据：解析层原样保留，渲染层（CSP）负责防执行。"""
    payload = json.dumps({"name": "N", "tasks": [{"prompt": XSS, "expected": "e"}]})
    data = parse_json(payload)
    assert data["tasks"][0]["prompt"] == XSS


# ---------------- parse_csv ----------------

def test_csv_two_columns_ok():
    data = parse_csv("prompt,expected\n1+1?,2\n2+2?,4\n")
    assert len(data["tasks"]) == 2
    assert data["tasks"][0]["test_cases"][0]["expected"] == "2"
    assert data["tasks"][1]["id"] == "T2"


def test_csv_full_columns_ok():
    data = parse_csv("id,dimension,prompt,expected,rubric_note,difficulty\n"
                     "t9,知识,p?,e,给分,困难\n")
    t = data["tasks"][0]
    assert t["id"] == "t9" and t["dimension"] == "知识"
    assert t["rubric_note"] == "给分" and t["difficulty"] == "困难"


def test_csv_header_case_and_space_insensitive():
    data = parse_csv("Prompt ,Expected\n1+1?,2\n")
    assert data["tasks"][0]["test_cases"][0]["expected"] == "2"


def test_csv_crlf_line_endings_ok():
    data = parse_csv("prompt,expected\r\n1+1?,2\r\n2+2?,4\r\n")
    assert len(data["tasks"]) == 2


def test_csv_quoted_field_with_comma():
    data = parse_csv('prompt,expected\n"有,逗号",2\n')
    assert data["tasks"][0]["prompt"] == "有,逗号"


def test_csv_missing_prompt_column_raises():
    with pytest.raises(ValueError, match="缺少 prompt 列"):
        parse_csv("expected,other\n2,x\n")


def test_csv_missing_expected_column_raises():
    with pytest.raises(ValueError, match="缺少 expected 列"):
        parse_csv("prompt,other\np,x\n")


def test_csv_all_empty_rows_raises():
    with pytest.raises(ValueError, match="没有有效的题目行"):
        parse_csv("prompt,expected\n,\n,\n")


def test_csv_empty_prompt_row_skipped():
    data = parse_csv("prompt,expected\n,p\n1+1?,2\n")
    assert len(data["tasks"]) == 1


def test_csv_bom_header_locked_behavior():
    """UTF-8 BOM 保留在首个列名中 → 按当前实现报缺列（锁定行为，不崩溃）。"""
    with pytest.raises(ValueError):
        parse_csv("\ufeffprompt,expected\n1+1?,2\n")


def test_csv_empty_content_raises():
    with pytest.raises(ValueError):
        parse_csv("")


# ---------------- parse_markdown ----------------

MD_FULL = """# 测试集
> 描述一 描述二
## 数学
### T1
**题目：** 1+1？
**期望：** 2
**评分标准：** 分步给分
补充说明行
### T2
**题目：** 2+2？
**期望：** 4
"""


def test_markdown_full_doc_ok():
    data = parse_markdown(MD_FULL)
    assert data["name"] == "测试集"
    assert data["description"] == "描述一 描述二"
    assert [t["id"] for t in data["tasks"]] == ["T1", "T2"]
    assert data["tasks"][0]["dimension"] == "数学"
    assert data["tasks"][0]["prompt"] == "1+1？\n补充说明行"
    assert data["tasks"][0]["test_cases"][0]["expected"] == "2"
    assert data["tasks"][0]["rubric_note"] == "分步给分"


def test_markdown_auto_numbering_when_empty_heading():
    data = parse_markdown("### \n**题目：** p\n**期望：** e\n### \n**题目：** p2\n**期望：** e2\n")
    assert [t["id"] for t in data["tasks"]] == ["T1", "T2"]


def test_markdown_no_expected_means_no_test_cases():
    data = parse_markdown("### T1\n**题目：** p\n")
    assert data["tasks"][0]["test_cases"] == []


def test_markdown_dimension_switch_affects_following_tasks():
    data = parse_markdown("## 数学\n### T1\n**题目：** p\n## 代码\n### T2\n**题目：** p2\n")
    assert data["tasks"][0]["dimension"] == "数学"
    assert data["tasks"][1]["dimension"] == "代码"


def test_markdown_no_tasks_raises():
    with pytest.raises(ValueError, match="未解析到任何题目"):
        parse_markdown("# 标题\n> 描述\n")


def test_markdown_missing_title_autogenerated():
    data = parse_markdown("### T1\n**题目：** p\n**期望：** e\n")
    assert AUTO_NAME.match(data["name"])


def test_markdown_xss_payload_passes_through_as_data():
    data = parse_markdown(f"### T1\n**题目：** {XSS}\n")
    assert data["tasks"][0]["prompt"] == XSS


def test_markdown_half_width_colon_labels():
    data = parse_markdown("### T1\n**题目:p**\n**期望:e**\n")
    assert data["tasks"][0]["prompt"] == "p"
    assert data["tasks"][0]["test_cases"][0]["expected"] == "e"


def test_markdown_auto_id_avoids_explicit_id():
    """空题号自动编号须避让显式 `### X`（issue #15 方向 3）。"""
    data = parse_markdown("### T1\n**题目：** p\n**期望：** e\n### \n**题目：** q\n**期望：** e2\n")
    assert [t["id"] for t in data["tasks"]] == ["T1", "T2"]


def test_markdown_duplicate_explicit_ids_rejected():
    with pytest.raises(DatasetValidationError, match=r"tasks\[1\]\.id: 与 tasks\[0\]\.id 重复（'X'）"):
        parse_markdown("### X\n**题目：** p\n**期望：** e\n### X\n**题目：** q\n**期望：** e2\n")


def test_markdown_auto_id_skips_explicit_id_in_later_block():
    """自动编号须预扫全文显式 id：后方 `### T1` 也须避让（issue #15 方向 3）。"""
    data = parse_markdown("### \n**题目：** p\n**期望：** e\n### T1\n**题目：** q\n**期望：** e2\n")
    assert [t["id"] for t in data["tasks"]] == ["T2", "T1"]


# ---------------- 多格式一致性（issue #15） ----------------

def test_duplicate_ids_rejected_consistently_across_formats():
    """等价无效输入（重复显式 id 'X'）在 JSON/CSV/Markdown 均抛同一校验类。"""
    with pytest.raises(DatasetValidationError):
        parse_json('{"tasks":[{"id":"X","prompt":"p1","expected":"e1"},'
                   '{"id":"X","prompt":"p2","expected":"e2"}]}')
    with pytest.raises(DatasetValidationError):
        parse_csv("id,prompt,expected\nX,q1,e1\nX,q2,e2\n")
    with pytest.raises(DatasetValidationError):
        parse_markdown("### X\n**题目：** p\n**期望：** e\n### X\n**题目：** q\n**期望：** e2\n")


# ---------------- parse_txt ----------------

TXT_FULL = """# 我的集
问题一 | 答案一
问题二\t答案二
续行补充
# 代码
第三题 | 答三
"""


def test_txt_pipe_and_tab_separated_ok():
    data = parse_txt(TXT_FULL)
    assert data["name"] == "我的集"
    assert len(data["tasks"]) == 3
    assert data["tasks"][0]["id"] == "T1"
    assert data["tasks"][0]["test_cases"][0]["expected"] == "答案一"
    assert data["tasks"][1]["test_cases"][0]["expected"] == "答案二"
    # 无分隔符续行并入上一题 prompt
    assert "续行补充" in data["tasks"][1]["prompt"]
    # `# 维度` 切换维度
    assert data["tasks"][0]["dimension"] == "自定义"
    assert data["tasks"][2]["dimension"] == "代码"


def test_txt_first_line_dimension_is_name_only():
    data = parse_txt("# 维度A\nq1 | e1\n# 维度B\nq2 | e2\n")
    assert data["name"] == "维度A"
    assert data["tasks"][0]["dimension"] == "自定义"
    assert data["tasks"][1]["dimension"] == "维度B"


def test_txt_line_without_separator_becomes_own_task():
    """无分隔符且无当前题时，该行自成一题（无期望 → 空 test_cases）。"""
    data = parse_txt("孤行\nq2 | e2\n")
    assert len(data["tasks"]) == 2
    assert data["tasks"][0]["test_cases"] == []


def test_txt_no_tasks_raises():
    with pytest.raises(ValueError, match="未解析到任何题目"):
        parse_txt("")
    with pytest.raises(ValueError, match="未解析到任何题目"):
        parse_txt("\n\n  \n")


def test_txt_missing_title_autogenerated():
    data = parse_txt("q | e\n")
    assert AUTO_NAME.match(data["name"])


def test_txt_xss_payload_passes_through_as_data():
    data = parse_txt(f"q | {XSS}\n")
    assert data["tasks"][0]["test_cases"][0]["expected"] == XSS


# ---------------- 注册表 ----------------

def test_registry_contains_supported_extensions():
    assert set(PARSER_REGISTRY) == {".json", ".csv", ".md", ".markdown", ".txt"}


def test_get_parser_known_extensions():
    assert get_parser(".json") is parse_json
    assert get_parser(".csv") is parse_csv
    assert get_parser(".md") is parse_markdown
    assert get_parser(".markdown") is parse_markdown
    assert get_parser(".txt") is parse_txt


def test_get_parser_unknown_returns_none():
    assert get_parser(".xlsx") is None
    assert get_parser(".py") is None


def test_get_parser_case_sensitive_locked():
    """文档约定 ext 需小写：大写扩展名按当前实现返回 None（锁定行为）。"""
    assert get_parser(".JSON") is None
    assert get_parser(".MD") is None


def test_get_parser_missing_dot_returns_none():
    assert get_parser("json") is None
    assert get_parser("") is None


def test_supported_extensions_sorted():
    assert supported_extensions() == [".csv", ".json", ".markdown", ".md", ".txt"]
