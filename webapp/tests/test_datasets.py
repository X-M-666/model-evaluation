# -*- coding: utf-8 -*-
"""数据集校验/解析单元测试（issue #11）。

覆盖 validate_json_dataset（完整/简化格式、默认值、恶意输入）与
parse_csv_dataset（列名容错、引号、空行、边界输入）的深层行为。
"""
from __future__ import annotations

import re

import pytest

from backend.engine.datasets import (
    DatasetValidationError,
    parse_csv_dataset,
    validate_json_dataset,
)

AUTO_NAME = re.compile(r"^评测集_\d{8}_\d{6}$")
CSV_NAME = re.compile(r"^CSV评测集_\d{8}_\d{6}$")


# ---------------- validate_json_dataset ----------------

def test_json_full_format_preserves_test_cases_and_rubric():
    data = validate_json_dataset(
        '{"name":"N","tasks":[{"id":"t1","dimension":"代码能力","prompt":"p",'
        '"test_cases":[{"input":"i","expected":"e"}],"rubric_note":"r"}]}'
    )
    t = data["tasks"][0]
    assert t["test_cases"] == [{"input": "i", "expected": "e"}]
    assert t["rubric_note"] == "r"
    assert t["dimension"] == "代码能力"


def test_json_simplified_format_builds_test_cases():
    data = validate_json_dataset('{"tasks":[{"prompt":"p","expected":"e"}]}')
    t = data["tasks"][0]
    assert t["test_cases"] == [{"input": "p"[:50], "expected": "e"}]
    assert t["rubric_note"].startswith("【仅评审可见】")


def test_json_simplified_format_no_expected_empty_test_cases():
    data = validate_json_dataset('{"tasks":[{"prompt":"p"}]}')
    assert data["tasks"][0]["test_cases"] == []


def test_json_default_fields():
    data = validate_json_dataset('{"tasks":[{"prompt":"p","expected":"e"}]}')
    t = data["tasks"][0]
    assert t["id"] == "T1"
    assert t["dimension"] == "自定义"
    assert t["benchmark"] == "自定义评测集"
    assert t["difficulty"] == "进阶"


def test_json_custom_fields_kept():
    data = validate_json_dataset(
        '{"tasks":[{"id":"x9","dimension":"数学","benchmark":"B","difficulty":"困难",'
        '"prompt":"p","expected":"e"}]}'
    )
    t = data["tasks"][0]
    assert t["id"] == "x9" and t["dimension"] == "数学"
    assert t["benchmark"] == "B" and t["difficulty"] == "困难"


def test_json_missing_name_autogenerated():
    data = validate_json_dataset('{"tasks":[{"prompt":"p"}]}')
    assert AUTO_NAME.match(data["name"])


def test_json_description_default_empty():
    data = validate_json_dataset('{"tasks":[{"prompt":"p"}]}')
    assert data["description"] == ""


def test_json_prompt_whitespace_stripped():
    data = validate_json_dataset('{"tasks":[{"prompt":"  p  ","expected":"e"}]}')
    assert data["tasks"][0]["prompt"] == "p"


def test_json_broken_raises():
    with pytest.raises(ValueError, match="JSON 解析失败"):
        validate_json_dataset("{{{")


def test_json_top_level_array_raises():
    with pytest.raises(ValueError, match="顶层必须是对象"):
        validate_json_dataset('[{"prompt":"p"}]')


def test_json_missing_tasks_raises():
    with pytest.raises(ValueError, match="缺少 tasks"):
        validate_json_dataset('{"name":"N"}')


def test_json_tasks_not_list_raises():
    with pytest.raises(ValueError, match="缺少 tasks"):
        validate_json_dataset('{"tasks":{}}')


def test_json_task_not_object_raises():
    with pytest.raises(ValueError, match="tasks\\[0\\] 不是对象"):
        validate_json_dataset('{"tasks":["x"]}')


def test_json_task_missing_prompt_raises():
    with pytest.raises(ValueError, match="缺少 prompt"):
        validate_json_dataset('{"tasks":[{"id":"t1"}]}')


def test_json_empty_test_cases_list_counts_as_simplified():
    """提供空 test_cases 列表但无 rubric/dimension → 按简化格式处理（锁定行为）。"""
    data = validate_json_dataset('{"tasks":[{"prompt":"p","expected":"e","test_cases":[]}]}')
    assert data["tasks"][0]["test_cases"] == [{"input": "p"[:50], "expected": "e"}]


# ---------------- parse_csv_dataset ----------------

def test_csv_simplified_defaults():
    data = parse_csv_dataset("prompt,expected\n1+1?,2\n")
    t = data["tasks"][0]
    assert t["id"] == "T1"
    assert t["dimension"] == "自定义"
    assert t["difficulty"] == "进阶"
    assert t["benchmark"] == "自定义评测集"
    assert t["rubric_note"].startswith("【仅评审可见】")
    assert t["test_cases"] == [{"input": "1+1?"[:50], "expected": "2"}]
    assert CSV_NAME.match(data["name"])
    assert data["description"] == "从 CSV 导入，共 1 题"


def test_csv_full_columns_ok():
    data = parse_csv_dataset(
        "id,dimension,prompt,expected,rubric_note,difficulty\n"
        "t9,知识,1+1?,2,给分,困难\n"
    )
    t = data["tasks"][0]
    assert t["id"] == "t9" and t["dimension"] == "知识"
    assert t["rubric_note"] == "给分" and t["difficulty"] == "困难"


def test_csv_header_case_insensitive():
    data = parse_csv_dataset("Prompt,Expected\n1+1?,2\n")
    assert data["tasks"][0]["test_cases"][0]["expected"] == "2"


def test_csv_header_padded_whitespace_ok():
    data = parse_csv_dataset("prompt , expected\n1+1?,2\n")
    assert data["tasks"][0]["test_cases"][0]["expected"] == "2"


def test_csv_crlf_ok():
    data = parse_csv_dataset("prompt,expected\r\n1+1?,2\r\n")
    assert len(data["tasks"]) == 1


def test_csv_quoted_comma_and_newline():
    data = parse_csv_dataset('prompt,expected\n"a,b",2\n"x\ny",3\n')
    assert data["tasks"][0]["prompt"] == "a,b"
    assert data["tasks"][1]["prompt"] == "x\ny"


def test_csv_empty_content_raises():
    with pytest.raises(ValueError, match="CSV 为空或格式错误"):
        parse_csv_dataset("")


def test_csv_header_only_raises():
    with pytest.raises(ValueError, match="没有有效的题目行"):
        parse_csv_dataset("prompt,expected\n")


def test_csv_missing_prompt_column_raises():
    with pytest.raises(ValueError, match="缺少 prompt 列"):
        parse_csv_dataset("expected,other\n2,x\n")


def test_csv_missing_expected_column_raises():
    with pytest.raises(ValueError, match="缺少 expected 列"):
        parse_csv_dataset("prompt,other\np,x\n")


def test_csv_all_empty_rows_raises():
    with pytest.raises(ValueError, match="没有有效的题目行"):
        parse_csv_dataset("prompt,expected\n,\n,\n")


def test_csv_empty_prompt_row_skipped_id_keeps_row_index():
    """空 prompt 行被跳过，但后续 id 按原始行号编号（锁定行为）。"""
    data = parse_csv_dataset("prompt,expected\n,p\n1+1?,2\n")
    assert [t["id"] for t in data["tasks"]] == ["T2"]


def test_csv_duplicate_ids_rejected():
    """重复显式 id（issue #15）→ 拒绝并指出重复位置与 id 值。"""
    with pytest.raises(DatasetValidationError, match=r"tasks\[1\]\.id.*重复.*'DUP'"):
        parse_csv_dataset("id,prompt,expected\nDUP,q1,e1\nDUP,q2,e2\n")


# ---------------- 类型边界 / ID 唯一性（issue #15 / R2-006） ----------------

def test_json_non_string_name_rejected():
    with pytest.raises(DatasetValidationError, match=r"^name: 必须是字符串"):
        validate_json_dataset('{"name":123,"tasks":[{"prompt":"p","expected":"e"}]}')


def test_json_non_string_description_rejected():
    with pytest.raises(DatasetValidationError, match=r"^description: 必须是字符串"):
        validate_json_dataset('{"description":[1],"tasks":[{"prompt":"p","expected":"e"}]}')


def test_json_non_string_prompt_rejected():
    with pytest.raises(DatasetValidationError, match=r"tasks\[0\]\.prompt: 必须是字符串"):
        validate_json_dataset('{"tasks":[{"prompt":123}]}')


def test_json_non_string_expected_rejected():
    with pytest.raises(DatasetValidationError, match=r"tasks\[0\]\.expected: 必须是字符串"):
        validate_json_dataset('{"tasks":[{"prompt":"p","expected":["e"]}]}')


def test_json_non_string_id_rejected():
    with pytest.raises(DatasetValidationError, match=r"tasks\[0\]\.id: 必须是字符串"):
        validate_json_dataset('{"tasks":[{"id":123,"prompt":"p","expected":"e"}]}')


def test_json_explicit_empty_id_rejected():
    with pytest.raises(DatasetValidationError, match=r"tasks\[0\]\.id: 去空白后不能为空"):
        validate_json_dataset('{"tasks":[{"id":"","prompt":"p","expected":"e"}]}')


def test_json_duplicate_ids_rejected_with_position():
    with pytest.raises(DatasetValidationError, match=r"tasks\[2\]\.id: 与 tasks\[0\]\.id 重复（'X'）"):
        validate_json_dataset(
            '{"tasks":[{"id":"X","prompt":"p1","expected":"e1"},'
            '{"id":"Y","prompt":"p2","expected":"e2"},'
            '{"id":"X","prompt":"p3","expected":"e3"}]}'
        )


def test_json_auto_id_avoids_explicit_id():
    """显式 id=T2 在后续任务：自动编号必须避让，不产生重复（issue #15 方向 3）。"""
    data = validate_json_dataset('{"tasks":[{"id":"T2","prompt":"p1","expected":"e1"},'
                                 '{"prompt":"p2","expected":"e2"}]}')
    assert [t["id"] for t in data["tasks"]] == ["T2", "T3"]


def test_json_explicit_id_after_auto_avoids_collision():
    """显式 id=T1 出现在自动编号任务之后：预扫机制保证自动编号不与之冲突。"""
    data = validate_json_dataset('{"tasks":[{"prompt":"p1","expected":"e1"},'
                                 '{"id":"T1","prompt":"p2","expected":"e2"}]}')
    assert [t["id"] for t in data["tasks"]] == ["T2", "T1"]


def test_json_test_cases_non_list_rejected():
    with pytest.raises(DatasetValidationError, match=r"tasks\[0\]\.test_cases: 必须是数组"):
        validate_json_dataset('{"tasks":[{"prompt":"p","test_cases":{"input":"i"}}]}')


def test_json_test_cases_entry_not_object_rejected():
    with pytest.raises(DatasetValidationError, match=r"tasks\[0\]\.test_cases\[0\]: 必须是对象"):
        validate_json_dataset('{"tasks":[{"prompt":"p","test_cases":["x"]}]}')


def test_json_test_cases_entry_non_string_expected_rejected():
    with pytest.raises(DatasetValidationError, match=r"tasks\[0\]\.test_cases\[0\]\.expected: 必须是字符串"):
        validate_json_dataset('{"tasks":[{"prompt":"p","test_cases":[{"input":"i","expected":5}]}]}')


def test_json_task_count_over_limit_rejected():
    tasks = ",".join(f'{{"id":"T{i}","prompt":"p{i}","expected":"e{i}"}}' for i in range(201))
    with pytest.raises(DatasetValidationError, match="题目数量超过上限 200"):
        validate_json_dataset(f'{{"tasks":[{tasks}]}}')


def test_json_duplicate_ids_across_headers_and_sources_rejected():
    """同一重复 id 在简化/完整格式混合出现同样被拒（格式一致性）。"""
    payload = '{"tasks":[{"id":"X","prompt":"p1","expected":"e1"},{"id":"X","prompt":"p2","expected":"e2"}]}'
    with pytest.raises(DatasetValidationError):
        validate_json_dataset(payload)


def test_csv_blank_id_cell_rejected_when_id_column_present():
    """id 列存在但单元格为空 → 显式空 id 拒绝（issue #15）。"""
    with pytest.raises(DatasetValidationError, match=r"tasks\[1\]\.id: 去空白后不能为空"):
        parse_csv_dataset("id,prompt,expected\nA,q1,e1\n,q2,e2\n")


def test_csv_no_id_column_auto_numbering_ok():
    data = parse_csv_dataset("prompt,expected\nq1,e1\nq2,e2\n")
    assert [t["id"] for t in data["tasks"]] == ["T1", "T2"]
